def run(repo):
    catalog=json.loads((repo/"Localization/master/catalog.json").read_text())
    assert catalog["upstream_commit"] == PIN, "Representative probes belong to another upstream commit"
    sources={entry["source"] for entry in catalog["entries"].values() if not entry.get("obsolete")}
    failures=[]; visible=0; keys=0
    for file,line,source in PROBES:
        if file == "OptiScaler/menu/MenuPages.h" and source in PERSISTED_KEYS:
            keys+=1
            if source in sources: failures.append(f"Technical key should be excluded: {file}:{line} {source!r}")
        else:
            visible+=1
            if source not in sources: failures.append(f"Missing representative: {file}:{line} {source!r}")
    for failure in failures: print(failure)
    print(f"active_catalog={len(sources)}, representative_visible={visible}, persisted_keys={keys}, failures={len(failures)}")
    print("Representative inclusion only; not a full coverage percentage or rendered-language assertion.")
    return bool(failures)

if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    raise SystemExit(run(parser.parse_args().repo))
