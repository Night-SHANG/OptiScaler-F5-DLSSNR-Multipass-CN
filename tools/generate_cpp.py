#!/usr/bin/env python3
from __future__ import annotations
import argparse, re
from pathlib import Path
from loclib import *

def c_bytes(s: str) -> str:
    # ASCII-only C literal. Use octal escapes to avoid \x hex-run ambiguity.
    b=s.encode('utf-8')
    out=[]
    for x in b:
        if x==0x22: out.append('\\"')
        elif x==0x5c: out.append('\\\\')
        elif x==0x0a: out.append('\\n')
        elif x==0x0d: out.append('\\r')
        elif x==0x09: out.append('\\t')
        elif 0x20 <= x < 0x7f: out.append(chr(x))
        else: out.append(f'\\{x:03o}')
    return ''.join(out)

def fnv1a64(s: str) -> int:
    value = 0xcbf29ce484222325
    for byte in s.encode('utf-8'):
        value ^= byte
        value = (value * 0x100000001b3) & 0xffffffffffffffff
    return value


def rendered_formats(catalog: dict, zh: dict):
    token = re.compile(r'%(?:\d+\$)?[-+#0 \'I]*(?:\d+|\*)?(?:\.\d+|\.\*)?(?:hh|h|ll|l|j|z|t|L)?[diuoxXfFeEgGaAcspn%]|(?<!\{)\{(?:\d+|[A-Za-z_][\w]*)?(?::[^{}]*)?\}(?!\})')
    rows = []
    raw_fields = {e['source']: e.get('raw_fields', []) for e in load_json(LOC/'composed-templates.json', [])}
    for key, entry in catalog.get('entries', {}).items():
        tr = zh.get('entries', {}).get(key, {})
        if entry.get('obsolete') or tr.get('source_hash') != entry.get('source_hash') or not tr.get('text'): continue
        source, target = entry['source'], tr['text']
        def split(value):
            parts, kinds, tokens, start = [], [], [], 0
            for m in token.finditer(value):
                if m.group() == '%%': continue
                # Prose percentages (e.g. 50% of) are not formatting fields.
                if m.start() and (value[m.start()-1].isdigit() or (value[m.start()-1] == '}' and format_tokens(value[:m.start()]))) and m.group().startswith('% '): continue
                parts.append(value[start:m.start()].replace('%%','%').replace('{{','{').replace('}}','}'))
                raw=m.group(); tokens.append(raw)
                kinds.append('p' if raw == '%s' and value[:m.start()].endswith('point') else 's' if raw[-1] in 'sc' or raw.startswith('{') and not re.search(r':[.0-9]*[dfxXeEgG]',raw) else 'n')
                start=m.end()
            parts.append(value[start:].replace('%%','%').replace('{{','{').replace('}}','}'))
            return parts,kinds,tokens
        sp,sk,st=split(source); tp,tk,tt=split(target)
        if not sk or st != tt or len(sp) != len(tp): continue
        if sum(map(len,sp)) < 3: continue
        for index in raw_fields.get(source, []):
            if index < len(sk): sk[index] = 'r'
        rows.append((sum(map(len,sp)), '\x1f'.join(sp), '\x1f'.join(tp), ''.join(sk)))
    return sorted(set(rows), reverse=True)

def render_header(catalog: dict, zh: dict) -> str:
    z=zh.get('entries',{}); rows=[]; seen_hashes={}
    for entry in catalog.get('entries',{}).values():
        source=entry.get('source',''); h=fnv1a64(source)
        if h in seen_hashes and seen_hashes[h] != source: raise ValueError('source hash collision')
        seen_hashes[h]=source
    for k,e in catalog.get('entries',{}).items():
        if e.get('obsolete'): continue
        tr=z.get(k,{})
        text=''
        state=tr.get('state','missing')
        if tr.get('source_hash')==e.get('source_hash') and state in ('reviewed','machine_translated'):
            text=tr.get('text','')
        rows.append((k,fnv1a64(e.get('source','')),text,state))
    rows.sort(key=lambda r:r[0])
    lines=[
        '// Generated by tools/generate_cpp.py. DO NOT EDIT.',
        '#pragma once',
        '#include <cstddef>',
        '#include <cstdint>',
        '#include <string_view>',
        'namespace OptiScalerCN::Generated {',
        'struct SourceHash { std::uint64_t value; };',
        'inline constexpr std::uint64_t HashSource(std::string_view text) noexcept {',
        '    std::uint64_t value = 0xcbf29ce484222325ULL;',
        '    for (unsigned char byte : text) { value ^= byte; value *= 0x100000001b3ULL; }',
        '    return value;',
        '}',
        'inline constexpr bool operator==(std::string_view text, SourceHash expected) noexcept { return HashSource(text) == expected.value; }',
        'inline constexpr bool operator==(SourceHash expected, std::string_view text) noexcept { return text == expected; }',
        'struct TranslationEntry { const char* key; SourceHash source; const char* zh; };',
        'inline constexpr TranslationEntry kTranslations[] = {'
    ]
    for k,source_hash,t,state in rows:
        lines.append(f'    {{"{c_bytes(k)}", {{0x{source_hash:016x}ULL}}, "{c_bytes(t)}"}}, // {state}')
    lines += ['};', 'struct RenderedFormat { const char* sourceParts; const char* targetParts; const char* kinds; };', 'inline constexpr RenderedFormat kRenderedFormats[] = {']
    for _, sp, tp, kinds in rendered_formats(catalog, zh):
        lines.append(f'    {{"{c_bytes(sp)}", "{c_bytes(tp)}", "{kinds}"}},')
    lines += ['    {"", "", ""}', '};','inline constexpr std::size_t kTranslationCount = sizeof(kTranslations) / sizeof(kTranslations[0]);','} // namespace OptiScalerCN::Generated','']
    return '\n'.join(lines)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--out',type=Path,required=True); ap.add_argument('--channel',choices=CHANNELS,default='master'); args=ap.parse_args()
    paths=localization_channel_paths(args.channel)
    cat=load_json(paths['catalog'],{}); zh=load_json(LOC/'zh-CN.json',{})
    rendered=render_header(cat, zh)
    args.out.parent.mkdir(parents=True,exist_ok=True); args.out.write_text(rendered,encoding='ascii')
    count=sum(1 for e in cat.get('entries',{}).values() if not e.get('obsolete'))
    print(f'generated {count} entries -> {args.out}')
if __name__=='__main__': main()
